def quarter_headers(quarter_label: str) -> list[str]:
    import re
    m = re.match(r"(Q[1-4]) FY(\d{2})", quarter_label or "")
    if not m:
        return ["Particulars", "Previous Year", "Previous Quarter", quarter_label or "Current", "QoQ %", "YoY %"]
    q, fy = m.group(1), int(m.group(2))
    prev_q_map = {"Q1": ("Q4", fy - 1), "Q2": ("Q1", fy), "Q3": ("Q2", fy), "Q4": ("Q3", fy)}
    pq, pfy = prev_q_map[q]
    return ["Particulars", f"{q} FY{fy - 1:02d}", f"{pq} FY{pfy:02d}", f"{q} FY{fy:02d}", "QoQ %", "YoY %"]


def _font(size: int, bold: bool = False):
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf" if bold else "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
    ]
    for p in candidates:
        if Path(p).exists():
            return ImageFont.truetype(p, size=size)
    return ImageFont.load_default()


def metric_to_row(m: Metric) -> list[str]:
    current = m.current_display or fmt_num(m.current)
    prev_q = m.previous_q_display or fmt_num(m.previous_quarter)
    prev_y = m.previous_y_display or fmt_num(m.previous_year)
    qoq = m.qoq_display or (fmt_bps(m.qoq_bps) if m.qoq_bps is not None else fmt_pct(m.qoq_pct))
    yoy = m.yoy_display or (fmt_bps(m.yoy_bps) if m.yoy_bps is not None else fmt_pct(m.yoy_pct))
    return [m.name, prev_y, prev_q, current, qoq, yoy]


def format_text(report: ResultReport) -> str:
    headers = quarter_headers(report.quarter_label)
    lines = [
        f"*{report.company_name}*",
        f"Unit: {report.unit}",
        "",
        "```",
        f"{headers[0]:<32} {headers[1]:>10} {headers[2]:>10} {headers[3]:>10} {headers[4]:>10} {headers[5]:>10}",
        "-" * 88,
    ]
    for m in report.metrics:
        row = metric_to_row(m)
        lines.append(f"{row[0]:<32} {row[1]:>10} {row[2]:>10} {row[3]:>10} {row[4]:>10} {row[5]:>10}")
    lines.extend(["```", "", f"Source: {report.source_exchange}"])
    return "\n".join(lines)


def render_png(report: ResultReport, output_path: str) -> str:
    rows = [quarter_headers(report.quarter_label)] + [metric_to_row(m) for m in report.metrics]
    widths = [270, 115, 115, 115, 120, 120]
    row_h = 36
    top_h = 95
    footer_h = 32
    width = sum(widths)
    height = top_h + row_h * len(rows) + footer_h

    img = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(img)
    bold = _font(16, True)
    normal = _font(14, False)
    small = _font(11, False)

    # Title region
    draw.text((18, 14), report.company_name, font=bold, fill=(15, 15, 15))
    draw.text((18, 44), f"Unit: {report.unit}", font=small, fill=(30, 30, 30))
    draw.text((width - 180, 44), report.consolidation.upper(), font=small, fill=(30, 30, 30))

    y = top_h
    green = (207, 239, 212)
    dark_green = (20, 89, 54)
    header_blue = (196, 217, 241)
    border = (80, 80, 80)

    # Header row
    x = 0
    for i, cell_w in enumerate(widths):
        fill = dark_green if i == 0 else header_blue
        draw.rectangle((x, y, x + cell_w, y + row_h), fill=fill, outline=border)
        draw.text((x + 8, y + 9), rows[0][i], font=_font(13, True), fill="white" if i == 0 else "#111111")
        x += cell_w
    y += row_h

    for r_idx, row in enumerate(rows[1:]):
        x = 0
        is_key = row[0] in {"Revenue", "Gross Profit", "EBITDA", "Profit Before Tax", "PAT"}
        for c_idx, cell_w in enumerate(widths):
            fill = green if not is_key else (176, 224, 187)
            draw.rectangle((x, y, x + cell_w, y + row_h), fill=fill, outline=border)
            text = row[c_idx]
            font = _font(13, is_key or c_idx == 0)
            tw = draw.textbbox((0, 0), text, font=font)[2]
            draw.text((x + (cell_w - tw) / 2 if c_idx else x + 8, y + 9), text, font=font, fill="#111111")
            x += cell_w
        y += row_h

    draw.text((18, height - 23), f"Automated report • Source: {report.source_exchange} • Generated by Quarterly Results Automation", font=small, fill="#333333")
    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    img.save(output_path, quality=95)
    return output_path


def payload_from_report(report: ResultReport) -> dict[str, Any]:
    return {
        "company_name": report.company_name,
        "quarter_label": report.quarter_label,
        "period_end": report.period_end,
        "consolidation": report.consolidation,
        "unit": report.unit,
        "source_exchange": report.source_exchange,
        "source_url": report.source_url,
        "metrics": [asdict(m) for m in report.metrics],
        "metadata": report.metadata,
    }
